/*                                                                     */
/* Keys are the Itanium-mangled kernel symbol names. The template's    */
/* C++ identifier is literally  dirty_templates_<mangled_name>.        */
/* Matching against cuFuncGetName / __cudaRegisterFunction output is   */
/* a plain strcmp.                                                     */
