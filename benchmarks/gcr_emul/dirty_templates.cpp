extern "C" gcr_template_fn_t gcr_lookup_template(const char *mangled_name)
{
    if (!mangled_name) return nullptr;
    for (const auto &e : g_tmpl_table) {
        if (std::strcmp(e.mangled_name, mangled_name) == 0) return e.fn;
    }
    return nullptr;
}
